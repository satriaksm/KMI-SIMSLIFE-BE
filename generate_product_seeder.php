$lines = explode("\n", trim($data));
$structuredData = [];
$currentMerchant = null;

foreach ($lines as $line) {
    $line = trim($line);
    if (empty($line)) continue;
    
    if (strpos($line, '|') === false) {
        $currentMerchant = $line;
        $structuredData[$currentMerchant] = [];
    } else {
        $parts = array_map('trim', explode('|', $line));
        $name = $parts[0];
        $price = (int)$parts[1];
        
        $variants = [];
        $variantStr = $parts[2];
        if ($variantStr !== '-') {
            $varParts = explode(',', $variantStr);
            foreach ($varParts as $v) {
                if (preg_match('/^(.*?)\(\+?(\d+)\)$/', trim($v), $matches)) {
                    $variants[] = [
                        'name' => trim($matches[1]),
                        'price' => (int)$matches[2],
                    ];
                }
            }
        }
        
        $addons = [];
        $addonStr = $parts[3];
        if ($addonStr !== '-') {
            $addonParts = explode(',', $addonStr);
            foreach ($addonParts as $a) {
                if (preg_match('/^(.*?)\(\+?(\d+)\)$/', trim($a), $matches)) {
                    $addons[] = [
                        'name' => trim($matches[1]),
                        'price' => (int)$matches[2],
                    ];
                }
            }
        }
        
        $structuredData[$currentMerchant][] = [
            'name' => $name,
            'price' => $price,
            'variants' => $variants,
            'addons' => $addons,
        ];
    }
}

